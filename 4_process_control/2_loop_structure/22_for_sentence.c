#include <stdio.h>
int main(){
    /*
    for语句结构：
    for(初始化表达式;测试表达式;更新表达式){
        循环体语句;
    }
    初始化表达式（初始化循环变量）->测试表达式（条件表达式）->真->循环体语句->更新表达式（更新循环变量的值）->测试表达式-> ...
    测试表达式->假->跳出for循环

    注意：
    初始化表达式、测试表达式、更新表达式都是可选的，但分号不可省略
    可以在循环体内修改循环变量的值，更新表达式可以为空
    */
    int sum=0;
    for (int i=1; i <=100; i++)
    {
        sum+=i;
    }
    printf("%d\n",sum);

    for (int i = 0,j =0; i <=5; i++,j++)
    {
        j+=2;
        printf("i=%d j=%d\n",i,j);
    }
    return 0;
}